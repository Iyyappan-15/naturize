import checkRateLimit from '../utils/rateLimit.js';

export default async function handler(req, res) {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") return res.status(200).end();
  if (req.method !== "POST") return res.status(405).json({ error: "Method Not Allowed" });

  const rateLimit = checkRateLimit(req, 10, 60000);
  if (!rateLimit.success) {
    return res.status(429).json({ error: "Too many requests. Please try again in a minute." });
  }

  const { review } = req.body;
  if (!review || typeof review !== "string" || review.trim().length === 0)
    return res.status(400).json({ error: "Review text is required." });

  if (review.trim().length > 3000)
    return res.status(400).json({ error: "Review too long. Keep it under 3,000 characters." });

  const groqKey = process.env.GROQ_API_KEY;
  if (!groqKey || groqKey.trim() === "")
    return res.status(500).json({ error: "Server configuration error." });

  const sanitized = review.trim().replace(/[<>]/g, "");

  const systemMessage = `You are an expert AI detection algorithm specialized in analyzing product reviews (Amazon, Zomato, etc.).
Your job is to determine the precise likelihood that a review was generated by AI (like ChatGPT) rather than written by a real human.

Use this internal rubric to calculate a precise AI probability score (0 to 100):
- Base AI Score: Start at 50 for completely neutral text.
- +10 to +25 for overly perfect grammar and corporate formatting (e.g., bullet points, "In conclusion").
- +10 to +30 for generic praise without personal context ("game-changer", "exceeded my expectations", "highly recommend").
- +10 to +20 for a robotic lack of specific sensory details (no mention of exact usage scenarios).
- -10 to -35 for human flaws: typos, lowercase sentences, run-on sentences, natural slang ("according to me", "kinda").
- -10 to -30 for highly specific, anecdotal complaints or praises that an AI wouldn't invent.

Calculate the final score based on these signals. The score MUST be a highly specific integer (e.g. 14, 27, 83) rather than a generic round number like 20, 50, or 80.

CRITICAL INSTRUCTION: You MUST respond ONLY with a valid JSON object. Do not include any other text.

Expected JSON schema:
{
  "score": <precise integer between 0 and 100>,
  "explanation": "<A 2-sentence explanation of your conclusion, citing specific phrases from the text>",
  "signals": [
    "<Signal 1 (e.g., 'Use of generic praise like \"game-changer\"')>",
    "<Signal 2>"
  ]
}`;

  const userMessage = `Analyze this review:\n\n${sanitized}`;

  const makeRequest = async (model) => fetch("https://api.groq.com/openai/v1/chat/completions", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Authorization": `Bearer ${groqKey.trim()}`
    },
    body: JSON.stringify({
      model,
      response_format: { type: "json_object" },
      messages: [
        { role: "system", content: systemMessage },
        { role: "user", content: userMessage }
      ],
      temperature: 0.5,
      max_tokens: 500,
    }),
  });

  try {
    let apiRes = await makeRequest("llama-4-scout-17b-16e-instruct");

    if (!apiRes.ok) {
      const errText = await apiRes.clone().text();
      let errJson;
      try { errJson = JSON.parse(errText); } catch { errJson = {}; }
      if (errJson?.error?.code === "model_not_found" || apiRes.status === 404) {
        apiRes = await makeRequest("llama-3.1-8b-instant");
      }
      if (!apiRes.ok) throw new Error(errJson?.error?.message || "Groq API error");
    }

    const json = await apiRes.json();
    let textOut = json.choices?.[0]?.message?.content || "";
    if (!textOut) throw new Error("Empty response from AI");
    
    // Attempt to parse JSON response
    let parsedResult;
    try {
      parsedResult = JSON.parse(textOut);
    } catch (e) {
      throw new Error("Failed to parse analysis results.");
    }

    res.status(200).json(parsedResult);
  } catch (error) {
    console.error("Fake Review Detector Error:", error);
    res.status(500).json({ error: error.message || "Something went wrong" });
  }
}
